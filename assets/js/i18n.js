function init() {
  applyLanguage(currentLang);
  renderAll();
  initializeMotion();
  initializeSectionNavigation();
  fetchLatestFromCloud();
}

function toggleLanguage() {
  startLanguageTransition();
  currentLang = currentLang === "en" ? "fr" : "en";
  localStorage.setItem("portfolio_lang", currentLang);
  applyLanguage(currentLang);
  renderAll();
  initializeMotion();
  replayHeroTextAnimation();
}

function applyLanguage(lang) {
  document.documentElement.lang = lang;
  document.documentElement.dir = "ltr";
  document.getElementById("langBtnText").textContent =
    lang === "en" ? "Français" : "English";
  const shortLangEl = document.getElementById("langBtnTextShort");
  if (shortLangEl) shortLangEl.textContent = lang === "en" ? "FR" : "EN";

  const dict = I18N[lang];
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key]) el.textContent = dict[key];
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (dict[key]) el.setAttribute("placeholder", dict[key]);
  });
  if (typeof updateCommandPaletteLanguage === "function") {
    updateCommandPaletteLanguage();
  }
}
